"""
Pull the extra 9-F-4 channels that Part 2 uses to cross-check the stick-slip period, reusing
extract_witsml.py's chunk discovery and parser unchanged.

Why this file exists: Part 2 asked to "pull more sections of well 9-F-4". Scanning every log object the
mirror holds for that well (all 11 under 1/log/1/* plus 2/1/1) shows there are NO further sections of
torque/WOB data to pull -- log 6 ("1/6/1", the 22 chunks Part 1 already used) is the only time-indexed log
carrying TORQUE_AVG + WOB_AVG, and it already spans the whole ~7-day record. What the mirror does hold is
independent measurements of the same week:
  - log 6 also carries TQ_IN_AMPS / TQ_IN_AMPS_AV / TQ_IN_AMPS_MX: top-drive motor current, a physically
    separate torque proxy that Part 1's KEEP_CURVES list dropped
  - log 8 ("1/8/1", 4 chunks) carries its own TORQUE, WOB, SURF_RPM, BIT_RPM series for the same week at a
    coarser (~15 s) sampling interval
Both turn out NOT to be usable as independent cross-checks, which is itself a finding this script reports:
  - TQ_IN_AMPS* are identically zero for the whole week (an unpopulated channel, like ROP in 9-F-9), so nothing
    is saved for them
  - log 8's TORQUE is the same sensor as log 6's TORQUE_AVG, resampled to ~15 s (identical in ~92% of matched
    rows), so it adds no independent information
Output: data/f4_log8_channels.csv (regenerated by this script; git-ignored, since it is 3.6 MB and reproducible).

    python extract_f4_extra.py
"""
import numpy as np
import pandas as pd

from extract_witsml import RAW_ROOT, list_chunk_files, parse_log_file  # noqa: F401  (RAW_ROOT documents the source)

WELL_FOLDER = "Norway-Statoil-NO%2015_%2447%24_9-F-4"

LOG6_EXTRA = ["TQ_IN_AMPS", "TQ_IN_AMPS_AV", "TQ_IN_AMPS_MX", "TQ_IN_AMPS_MN"]
LOG8_KEEP = ["RigActivityCode", "Depth", "BITDEP", "WOB", "TORQUE", "SURF_RPM", "BIT_RPM", "HKLD"]


def load_log(log_path, keep, dest_dir="raw_xml"):
    import os
    os.makedirs(dest_dir, exist_ok=True)
    files = list_chunk_files(WELL_FOLDER, log_path, dest_dir)
    full = pd.concat([parse_log_file(f) for f in files], ignore_index=True)
    full["Time"] = pd.to_datetime(full["Time"])
    full = full.sort_values("Time").drop_duplicates(subset="Time").reset_index(drop=True)
    cols = ["Time"] + [c for c in keep if c in full.columns]
    out = full[cols].copy()
    for c in cols[1:]:
        out[c] = pd.to_numeric(out[c], errors="coerce")
    print(f"  {log_path}: {len(files)} chunk(s), columns kept: {cols[1:]}, shape {out.shape}, "
          f"{out['Time'].min()} to {out['Time'].max()}")
    return out


def main():
    print("Extracting extra 9-F-4 channels...")
    log6 = load_log("1/log/1/6/1", LOG6_EXTRA)
    print("\nLog 6 motor-current channels (TQ_IN_AMPS*):")
    for c in LOG6_EXTRA:
        print(f"  {c}: {log6[c].nunique()} distinct value(s), max {log6[c].max()}")
    log8 = load_log("1/log/1/8/1", LOG8_KEEP)
    log8.to_csv("data/f4_log8_channels.csv", index=False)
    print("saved data/f4_log8_channels.csv")

    # Is log 8's TORQUE an independent measurement, or log 6's TORQUE_AVG resampled?
    log6_main = pd.read_csv("data/f4_drilling_telemetry.csv", parse_dates=["Time"])[["Time", "TORQUE_AVG", "TORQUE_MAX"]]
    m = pd.merge_asof(log8.sort_values("Time"), log6_main.sort_values("Time"), on="Time", direction="nearest",
                      tolerance=pd.Timedelta("8s")).dropna(subset=["TORQUE_AVG"])
    ok = m[(m["TORQUE"] < 15000) & (m["TORQUE_MAX"] < 15000) & (m["TORQUE"] > 0) & (m["TORQUE_AVG"] > 0)]
    print(f"\nLog 8 TORQUE vs. log 6 TORQUE_AVG: {len(ok)} matched rows (log 8 median spacing "
          f"{log8['Time'].diff().dt.total_seconds().median():.0f} s vs. log 6 "
          f"{log6['Time'].diff().dt.total_seconds().median():.0f} s); identical in "
          f"{np.isclose(ok['TORQUE'], ok['TORQUE_AVG']).mean()*100:.0f}% of rows, Spearman correlation "
          f"{ok['TORQUE'].corr(ok['TORQUE_AVG'], method='spearman'):.3f}")


if __name__ == "__main__":
    main()
